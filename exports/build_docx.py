# ---------- helpers ----------
def field(paragraph, instr, placeholder="1"):
    fld = OxmlElement("w:fldSimple"); fld.set(qn("w:instr"), instr)
    r = OxmlElement("w:r"); t = OxmlElement("w:t"); t.text = placeholder
    r.append(t); fld.append(r); paragraph._p.append(fld)

def shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd"); shd.set(qn("w:val"),"clear")
    shd.set(qn("w:color"),"auto"); shd.set(qn("w:fill"),fill); tcPr.append(shd)

def cell_text(cell, text, bold=False, color=None, size=9.0, align=None):
    cell.text = ""
    parts = str(text).split("\n")
    for i, part in enumerate(parts):
        p = cell.paragraphs[0] if i == 0 else cell.add_paragraph()
        p.paragraph_format.space_after = Pt(0); p.paragraph_format.space_before = Pt(0)
        if align: p.alignment = align
        run = p.add_run(part); run.font.name = "Arial"; run.font.size = Pt(size)
        run.bold = bold
        if color: run.font.color.rgb = RGBColor.from_string(color)

def fix_layout(t):
    tblPr = t._tbl.tblPr
    lay = OxmlElement("w:tblLayout"); lay.set(qn("w:type"),"fixed"); tblPr.append(lay)

def add_table(headers, rows, widths, size=9.0, header_fill=BLUE, zebra=True):
    t = doc.add_table(rows=1, cols=len(headers)); t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER; t.autofit = False; fix_layout(t)
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]; cell_text(c, h, bold=True, color="FFFFFF", size=size)
        shade(c, header_fill)
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cell_text(cells[i], val, size=size)
            if zebra and ri % 2 == 1: shade(cells[i], GREY)
    for r in t.rows:
        for i, w in enumerate(widths): r.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t

def callout(text, fill=WARN, label="ВНИМАНИЕ"):
    t = doc.add_table(rows=1, cols=1); t.style = "Table Grid"; t.autofit = False; fix_layout(t)
    c = t.rows[0].cells[0]; c.width = Cm(CONTENT_CM); shade(c, fill)
    c.text = ""
    p = c.paragraphs[0]
    r = p.add_run(label + ": "); r.bold = True; r.font.size = Pt(9.5); r.font.name = "Arial"
    r.font.color.rgb = RGBColor.from_string("9C5700")
    r2 = p.add_run(text); r2.font.size = Pt(9.5); r2.font.name = "Arial"
    doc.add_paragraph().paragraph_format.space_after = Pt(2)

def h1(s): doc.add_heading(s, level=1)
def h2(s): doc.add_heading(s, level=2)
def para(s, size=11, bold=False, italic=False, after=4, color=None):
    p = doc.add_paragraph(); p.paragraph_format.space_after = Pt(after)
    r = p.add_run(s); r.bold = bold; r.italic = italic; r.font.name = "Arial"; r.font.size = Pt(size)
    if color: r.font.color.rgb = RGBColor.from_string(color)
    return p
def bullet(s, size=10.5):
    p = doc.add_paragraph(style="List Bullet"); p.paragraph_format.space_after = Pt(2)
